/** 고른 용도 (큰 분류 번호 + 세부) */
export interface UsePick {
  no: string
  sub?: string
}

export function useLabel(p: UsePick | null | undefined): string {
  if (!p) return '용도 미정'
  const c = USE_CLASSES.find((u) => u.no === p.no)
  if (!c) return '용도 미정'
  return p.sub && p.sub !== c.name ? `${c.name} · ${p.sub}` : c.name
}

